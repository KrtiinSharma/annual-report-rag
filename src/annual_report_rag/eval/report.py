"""Collect docs/results/*.json into summary.json (served to the UI) and RESULTS.md."""

import json

from annual_report_rag.config import get_settings

RAG_COLS = [
    ("faithfulness", "Faithfulness"),
    ("answer_relevancy", "Answer relevancy"),
    ("context_recall", "Context recall"),
    ("hit@5", "Page hit@5"),
    ("cited_page_hit", "Cited page hit"),
    ("latency_s", "Latency (s)"),
]
RETRIEVAL_COLS = [
    ("hit@1", "hit@1"),
    ("hit@3", "hit@3"),
    ("hit@5", "hit@5"),
    ("hit@10", "hit@10"),
    ("mrr", "MRR"),
]


def _fmt(v) -> str:
    return "–" if v is None else f"{v:.3f}" if isinstance(v, float) else str(v)


def _table(rows: list[dict], cols) -> str:
    head = "| Experiment | n | " + " | ".join(label for _, label in cols) + " |"
    sep = "|---|---|" + "---|" * len(cols)
    lines = [head, sep]
    for r in rows:
        agg = r["aggregate"]
        n = r.get("n", len(r.get("rows", [])))
        lines.append(
            f"| {r['name']} | {n} | " + " | ".join(_fmt(agg.get(k)) for k, _ in cols) + " |"
        )
    return "\n".join(lines)


def write_report():
    results_dir = get_settings().results_dir
    experiments = []
    for path in sorted(results_dir.glob("*.json")):
        if path.name == "summary.json":
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        experiments.append(data)

    summary = [
        {k: e.get(k) for k in ("name", "kind", "config", "n", "aggregate")}
        | {"n": e.get("n", len(e.get("rows", [])))}
        for e in experiments
    ]
    (results_dir / "summary.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")

    rag = [e for e in experiments if e["kind"] == "rag"]
    retrieval = [e for e in experiments if e["kind"] == "retrieval"]
    md = ["# Evaluation results", "", "Generated by `uv run arr-eval report`.", ""]
    if retrieval:
        md += ["## Retrieval only: chunking strategies", "", _table(retrieval, RETRIEVAL_COLS), ""]
    if rag:
        md += ["## End-to-end RAG (RAGAS)", "", _table(rag, RAG_COLS), ""]
    path = results_dir / "RESULTS.md"
    path.write_text("\n".join(md), encoding="utf-8")
    return path
